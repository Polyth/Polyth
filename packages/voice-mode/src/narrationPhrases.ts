export const NARRATION_PHRASES: Readonly<Record<Locale, NarrationPhrases>> = {
  en, uk, de, fr, pl, "pt-BR": ptBR, pt, it, es, "zh-CN": zhCN, bg, ar,
};

export function narrationPhrases(locale: string): NarrationPhrases {
  return (NARRATION_PHRASES as Readonly<Record<string, NarrationPhrases>>)[locale] ?? en;
}

/** The catalog for a speech language ("uk-UA", "pt-PT", "auto" resolved by
 *  the caller), or `fallback` when Polyth has no such locale. */
export function narrationLocale(lang: string, fallback: string): string {
  const known = NARRATION_PHRASES as Readonly<Record<string, NarrationPhrases>>;
  const value = lang.trim();
  if (known[value]) return value;
  const [base = "", region = ""] = value.split(/[-_]/);
  const lower = base.toLowerCase();
  if (lower === "pt") return region.toUpperCase() === "BR" ? "pt-BR" : "pt";
  if (lower === "zh") return "zh-CN";
  return known[lower] ? lower : fallback;
}
