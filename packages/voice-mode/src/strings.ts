export function voiceModeStrings(locale: string): VoiceModeStrings {
  return (VOICE_MODE_STRINGS as Readonly<Record<string, VoiceModeStrings>>)[locale] ?? en;
}

/** Fill `{name}` placeholders. */
export function formatVoiceString(template: string, values: Readonly<Record<string, string>>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => values[key] ?? match);
}
