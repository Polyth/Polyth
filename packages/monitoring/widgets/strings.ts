export const MONITORING_TABLES: Readonly<Record<string, Table>> = { de, fr, pl, "pt-BR": ptBR, it, es, "zh-CN": zhCN, bg, ar, pt };

/** Exact locale first, then its language (`zh` → `zh-CN`); English when neither exists. */
export function monitoringWords(locale: string): Words {
  const language = locale.split("-")[0]!.toLowerCase();
  if (language === "uk") return (_english, ukrainian) => ukrainian;
  const table = MONITORING_TABLES[locale] ?? MONITORING_TABLES[language] ?? (language === "zh" ? MONITORING_TABLES["zh-CN"] : undefined);
  return (english) => table?.[english] ?? english;
}
