const CATALOGS: Readonly<Record<string, WebSearchCopy>> = { en: EN, uk: UK, de: DE, fr: FR, pl: PL, "pt-BR": PT_BR, pt: PT, it: IT, es: ES, "zh-CN": ZH_CN, bg: BG, ar: AR };

export function webSearchCopy(locale: string): WebSearchCopy {
  const language = locale.split("-")[0]!.toLowerCase();
  return CATALOGS[locale] ?? CATALOGS[language] ?? (language === "zh" ? CATALOGS["zh-CN"]! : EN);
}
