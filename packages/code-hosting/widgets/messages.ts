const CATALOGS: Readonly<Record<string, Record<keyof typeof en, string>>> = { en, uk, de, fr, pl, "pt-BR": ptBR, pt, it, es, "zh-CN": zhCN, bg, ar };

export function hostingMessage(locale: string, key: string, values: Record<string, string | number> = {}): string | undefined {
  const language = locale.split("-")[0]!.toLowerCase();
  const catalog = CATALOGS[locale] ?? CATALOGS[language] ?? (language === "zh" ? CATALOGS["zh-CN"]! : en);
  const template = catalog[key as keyof typeof en];
  if (template === undefined) return undefined;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => values[name] === undefined ? match : String(values[name]));
}
