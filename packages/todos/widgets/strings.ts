export const TODO_LOCALES: Readonly<Record<string, TodoStrings>> = {
  en, uk, de, fr, pl, "pt-BR": ptBR, pt, it, es, "zh-CN": zhCN, bg, ar,
};

/** Exact host locale first, then its language (`uk-UA` → `uk`, `zh` → `zh-CN`), then English. */
export function todoStrings(locale: string): TodoStrings {
  if (TODO_LOCALES[locale]) return TODO_LOCALES[locale]!;
  const language = locale.split("-")[0]!.toLowerCase();
  return TODO_LOCALES[language] ?? Object.entries(TODO_LOCALES).find(([id]) => id.startsWith(`${language}-`))?.[1] ?? en;
}

export const fill = (template: string, values: Record<string, string | number>): string =>
  template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));

const safeLocale = (locale: string): string => {
  try {
    return Intl.NumberFormat.supportedLocalesOf(locale).length ? locale : "en";
  } catch {
    return "en";
  }
};

/** Locale-aware number formatting, the same Intl path the host's `formatNumber` uses. */
export function todoFormat(locale: string) {
  const loc = safeLocale(locale);
  const unit = (value: number, name: "hour" | "minute" | "second") =>
    new Intl.NumberFormat(loc, { style: "unit", unit: name, unitDisplay: "short" }).format(value);
  return {
    count: (value: number) => new Intl.NumberFormat(loc).format(value),
    tokens: (value: number) => new Intl.NumberFormat(loc, { notation: "compact" }).format(Math.round(value)),
    cost: (value: number) => value > 0 && value < 0.01
      ? `<${new Intl.NumberFormat(loc, { style: "currency", currency: "USD" }).format(0.01)}`
      : new Intl.NumberFormat(loc, { style: "currency", currency: "USD" }).format(value),
    /** `1h 05m`-style spans with localized unit symbols; seconds only under an hour. */
    elapsed: (ms: number) => {
      const total = Math.floor(Math.max(0, ms) / 1000);
      const hours = Math.floor(total / 3600);
      const minutes = Math.floor((total % 3600) / 60);
      const seconds = total % 60;
      if (hours > 0) return `${unit(hours, "hour")} ${unit(minutes, "minute")}`;
      if (minutes > 0) return `${unit(minutes, "minute")} ${unit(seconds, "second")}`;
      return unit(seconds, "second");
    },
  };
}
