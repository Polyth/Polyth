const CATALOGS: Readonly<Record<string, BtwStrings>> = { en, uk, de, fr, pl, "pt-BR": ptBR, pt, it, es, "zh-CN": zhCN, bg, ar };

export function btwStrings(locale: string): BtwStrings {
  const language = locale.split("-")[0]!.toLowerCase();
  return CATALOGS[locale] ?? CATALOGS[language] ?? (language === "zh" ? CATALOGS["zh-CN"]! : en);
}
