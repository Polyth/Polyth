const BUNDLES: Record<GalleryLocale, Record<string, string>> = { en: EN, uk: UK, de: DE, fr: FR, pl: PL, "pt-BR": PT_BR, pt: PT, it: IT, es: ES, "zh-CN": ZH_CN, bg: BG, ar: AR };

export type GalleryTranslate = (key: string, values?: Record<string, string | number>) => string;

export function isGalleryLocale(value: string): value is GalleryLocale {
  return Object.hasOwn(BUNDLES, value);
}

export function createGalleryTranslate(locale: string): GalleryTranslate {
  const language = locale.split("-")[0]!.toLowerCase();
  const bundle = isGalleryLocale(locale) ? BUNDLES[locale] : isGalleryLocale(language) ? BUNDLES[language] : language === "zh" ? BUNDLES["zh-CN"] : EN;
  return (key, values = {}) => {
    const template = bundle[key] ?? EN[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => {
      const value = values[name];
      return value === undefined || value === null ? match : String(value);
    });
  };
}
