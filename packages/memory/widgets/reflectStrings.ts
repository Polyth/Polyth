export type ReflectStrings = typeof en;

const CATALOGS: Readonly<Record<string, ReflectStrings>> = { en, uk, de, fr, pl, "pt-BR": ptBR, pt, it, es, "zh-CN": zhCN, bg, ar };

export function reflectStrings(locale: string | undefined): ReflectStrings {
  if (!locale) return en;
  const language = locale.split("-")[0]!.toLowerCase();
  return CATALOGS[locale] ?? CATALOGS[language] ?? (language === "zh" ? CATALOGS["zh-CN"]! : en);
}

export function format(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => key in values ? String(values[key]) : match);
}

/** Human reason for a server instruction-write failure code. */
export function failureReason(t: ReflectStrings, code: string): string {
  const key = `reason_${code}` as keyof ReflectStrings;
  return key in t ? t[key] : t["reason_write-failed"];
}
