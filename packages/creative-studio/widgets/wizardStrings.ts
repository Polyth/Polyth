const LOCALES: Readonly<Record<string, WizardStrings>> = { en, uk, de, fr, pl, "pt-BR": ptBR, pt, it, es, "zh-CN": zhCN, bg, ar };

export function wizardStrings(locale: string): WizardStrings {
  const language = locale.split("-")[0]!.toLowerCase();
  return LOCALES[locale] ?? LOCALES[language] ?? (language === "zh" ? zhCN : en);
}

export const wl = (t: WizardStrings, key: string): string => (t as Record<string, string>)[key] ?? key;
