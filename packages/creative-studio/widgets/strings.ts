const LOCALES: Readonly<Record<string, StudioStrings>> = { en, uk, de, fr, pl, "pt-BR": ptBR, pt, it, es, "zh-CN": zhCN, bg, ar };

export function studioStrings(locale: string): StudioStrings {
  const language = locale.split("-")[0]!.toLowerCase();
  return LOCALES[locale] ?? LOCALES[language] ?? (language === "zh" ? zhCN : en);
}

export const fill = (template: string, values: Record<string, string | number>): string =>
  template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));

export const label = (t: StudioStrings, key: string): string =>
  (t as Record<string, string>)[key] ?? key;

export const compact = (value: number) =>
  value >= 1_000_000 ? `${(value / 1_000_000).toFixed(1)}M` : value >= 1000 ? `${Math.round(value / 1000)}k` : String(value);
