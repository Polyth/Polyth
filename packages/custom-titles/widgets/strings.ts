const CATALOGS: Readonly<Record<string, CustomTitlesStrings>> = {
  en, uk, de, fr, pl, "pt-BR": ptBR, pt, it, es, "zh-CN": zhCN, bg, ar,
};

/** Exact host locale first, then its language (`uk-UA` → `uk`, `zh` → `zh-CN`), then English. */
export function customTitlesStrings(locale: string): CustomTitlesStrings {
  const language = locale.split("-")[0]!.toLowerCase();
  return CATALOGS[locale] ?? CATALOGS[language] ?? (language === "zh" ? zhCN : en);
}
