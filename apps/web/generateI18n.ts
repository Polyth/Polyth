/**
 * Generates the shell's package-owned i18n integration from package manifests.
 *
 *   node --experimental-strip-types apps/web/generateI18n.ts          # write
 *   node --experimental-strip-types apps/web/generateI18n.ts --check  # verify
 *
 * Output, both under apps/web/src/i18n/catalogs/:
 *   - packageCatalogs.generated.ts: the always-bundled English package
 *     catalogs and the union of every merged package's MessageKey type.
 *   - <locale>.ts: one dynamic-import chunk per non-English locale.
 *
 * A package participates when its manifest declares both "./i18n" and
 * "./i18n/*" and its English catalog uses the shell's namespaced (dotted)
 * key contract. Self-hosted catalogs that keep bare identifier keys and their
 * own text lookup (for example @polyth/gitlab) are deliberately not merged, so
 * the shared tr() namespace stays exactly the set the shell had by hand.
 *
 * Package order is the sorted package directory id, so output is deterministic
 * and a removed package simply disappears on the next run.
 */
import { readFile, rename, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { LOCALES, type Locale } from "@polyth/contracts";
import { discoverWebPackages } from "./webPackages.ts";

const here = import.meta.dirname;
const repositoryRoot = resolve(here, "../..");
const defaultPackagesDir = resolve(repositoryRoot, "packages");
const i18nSourceDir = resolve(here, "src/i18n");
const catalogsDir = resolve(i18nSourceDir, "catalogs");
export const packageCatalogsPath = resolve(catalogsDir, "packageCatalogs.generated.ts");

const GENERATED_HEADER = "// @generated by `npm run i18n:generate` — do not edit.\n";

/** One package whose catalog the shell merges into the runtime translation. */
export interface ShellI18nPackage {
  /** Package directory id; drives aliases, type names and output order. */
  id: string;
  /** Package manifest name; drives the import specifier. */
  packageName: string;
  /** Locales that ship a resolvable catalog module for this package. */
  locales: Locale[];
}

/** A generated file and the exact bytes it must contain. */
export interface RenderedI18nFile {
  path: string;
  contents: string;
}

const isFile = async (path: string): Promise<boolean> => {
  try {
    return (await stat(path)).isFile();
  } catch {
    return false;
  }
};

const pascalCase = (value: string): string =>
  value
    .split(/[^A-Za-z0-9]+/)
    .filter((part) => part.length > 0)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join("");

const aliasFor = (id: string): string => `p_${id.replaceAll(/[^A-Za-z0-9]/g, "_")}`;

const messageKeyName = (id: string): string => `${pascalCase(id)}MessageKey`;

/** pt-BR -> ptBR, zh-CN -> zhCN, uk -> uk (the export name in a locale file). */
export const localeIdentifier = (locale: Locale): string => {
  const [head, ...rest] = locale.split("-");
  return head! + rest.map((part) => part[0]!.toUpperCase() + part.slice(1)).join("");
};

// Top-level keys of a flat `export const en = { ... } as const;` catalog. The
// shell contract uses quoted, dotted namespaced keys; a self-hosted catalog
// with bare identifier keys is not part of that namespace.
const CATALOG_KEY =
  /^[ \t]*(?:"((?:[^"\\]|\\.)+)"|'((?:[^'\\]|\\.)+)'|([A-Za-z_$][\w$]*))[ \t]*:/;

const catalogKeys = (source: string): string[] =>
  source.split("\n").flatMap((line) => {
    const match = CATALOG_KEY.exec(line);
    if (!match) return [];
    return [match[1] ?? match[2] ?? match[3]!];
  });

const sourceExportsConst = async (path: string, name: string): Promise<boolean> => {
  const source = await readFile(path, "utf8");
  return new RegExp(`export const ${name}\\b`).test(source);
};

/** Discover every web package the shell should merge, sorted by package id. */
export async function discoverShellI18nPackages(
  packagesDir: string = defaultPackagesDir,
): Promise<ShellI18nPackage[]> {
  const discovered: ShellI18nPackage[] = [];
  for (const pkg of await discoverWebPackages(packagesDir)) {
    const manifest = JSON.parse(await readFile(join(pkg.dir, "package.json"), "utf8")) as {
      exports?: Record<string, unknown>;
    };
    const exportsMap = manifest.exports ?? {};
    const indexExport = exportsMap["./i18n"];
    if (typeof indexExport !== "string" || typeof exportsMap["./i18n/*"] !== "string") continue;
    const i18nDir = dirname(resolve(pkg.dir, indexExport));
    const englishFile = join(i18nDir, "en.ts");
    if (!(await isFile(englishFile))) continue;
    const englishKeys = catalogKeys(await readFile(englishFile, "utf8"));
    if (englishKeys.length === 0 || englishKeys.some((key) => !key.includes("."))) continue;
    const locales: Locale[] = [];
    for (const locale of LOCALES) {
      const file = join(i18nDir, `${locale}.ts`);
      if (!(await isFile(file))) continue;
      if (!(await sourceExportsConst(file, localeIdentifier(locale)))) continue;
      locales.push(locale);
    }
    if (!locales.includes("en")) continue;
    discovered.push({ id: pkg.id, packageName: pkg.packageName, locales });
  }
  return discovered.sort((left, right) => left.id.localeCompare(right.id));
}

/** The always-bundled English catalog list and the TranslationKey union. */
export function renderPackageCatalogs(packages: readonly ShellI18nPackage[]): string {
  const typeImports = packages.map(
    (pkg) => `import type { ${messageKeyName(pkg.id)} } from "${pkg.packageName}/i18n";`,
  );
  const valueImports = packages.map(
    (pkg) => `import { en as ${aliasFor(pkg.id)} } from "${pkg.packageName}/i18n/en";`,
  );
  const union = packages.length === 0
    ? ["  never;"]
    : packages.map((pkg, index) =>
      `  | ${messageKeyName(pkg.id)}${index === packages.length - 1 ? ";" : ""}`);
  const catalogs = packages.map((pkg) => `  ${aliasFor(pkg.id)},`);
  return [
    GENERATED_HEADER,
    "// The shell's always-bundled English package catalogs plus the union of",
    "// every merged package's message keys. Order is the sorted package id.",
    ...typeImports,
    "",
    ...valueImports,
    "",
    "export type PackageMessageKey =",
    ...union,
    "",
    "export const packageEnCatalogs: ReadonlyArray<Record<string, string>> = [",
    ...catalogs,
    "];",
    "",
  ].join("\n");
}

/** One dynamic-import locale chunk: the app catalog plus its package parts. */
export function renderLocaleCatalog(
  locale: Locale,
  packages: readonly ShellI18nPackage[],
): string {
  const identifier = localeIdentifier(locale);
  const included = packages.filter((pkg) => pkg.locales.includes(locale));
  const imports = included.map(
    (pkg) =>
      `import { ${identifier} as ${aliasFor(pkg.id)} } from "${pkg.packageName}/i18n/${locale}";`,
  );
  const parts = included.map((pkg) => `  ${aliasFor(pkg.id)},`);
  return [
    GENERATED_HEADER,
    "// Statically imported ONLY via dynamic import() in ../index.ts so each",
    "// locale ships as its own chunk.",
    `import { ${identifier} as app } from "../locales/${locale}.ts";`,
    ...imports,
    "",
    "const parts: Array<Record<string, string>> = [app,",
    ...parts,
    "];",
    "",
    "export const catalog: Record<string, string> = Object.assign({}, ...parts);",
    "",
  ].join("\n");
}

/** Every generated file with its would-be contents. */
export async function renderI18nFiles(
  packagesDir: string = defaultPackagesDir,
): Promise<RenderedI18nFile[]> {
  const packages = await discoverShellI18nPackages(packagesDir);
  const files: RenderedI18nFile[] = [
    { path: packageCatalogsPath, contents: renderPackageCatalogs(packages) },
  ];
  for (const locale of LOCALES) {
    if (locale === "en") continue;
    files.push({
      path: resolve(catalogsDir, `${locale}.ts`),
      contents: renderLocaleCatalog(locale, packages),
    });
  }
  return files;
}

/** Committed files whose bytes differ from the freshly rendered output. */
export async function checkI18n(
  packagesDir: string = defaultPackagesDir,
): Promise<string[]> {
  const mismatches: string[] = [];
  for (const file of await renderI18nFiles(packagesDir)) {
    let committed = "";
    try {
      committed = await readFile(file.path, "utf8");
    } catch {
      committed = "";
    }
    if (committed !== file.contents) mismatches.push(relative(repositoryRoot, file.path));
  }
  return mismatches;
}

async function main(): Promise<void> {
  const check = process.argv.includes("--check");
  const files = await renderI18nFiles();
  if (check) {
    const mismatches = await checkI18n();
    if (mismatches.length > 0) {
      console.error(`Generated i18n catalogs are stale: ${mismatches.join(", ")}`);
      console.error("Run `npm run i18n:generate` and commit the result.");
      process.exitCode = 1;
      return;
    }
    console.log("Generated i18n catalogs are up to date.");
    return;
  }
  let written = 0;
  for (const file of files) if (await replaceIfChanged(file.path, file.contents)) written += 1;
  console.log(`Generated ${files.length} i18n catalog files (${written} changed).`);
}

/** The catalogs are committed and read by every build: an interrupted run must
 *  never leave a truncated one, so each changed file is written beside the
 *  target (ignored `*.polyth-tmp.*`) and renamed over it. */
async function replaceIfChanged(path: string, contents: string): Promise<boolean> {
  if (await readFile(path, "utf8").then((current) => current === contents, () => false)) return false;
  const temp = `${path}.polyth-tmp.${process.pid}`;
  await writeFile(temp, contents);
  await rename(temp, path);
  return true;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
