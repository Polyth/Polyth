#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const manifest = resolve(here, "../ios/App/CapApp-SPM/Package.swift");
let source = await readFile(manifest, "utf8");

if (!source.includes('name: "PolythLinkCore"')) {
  const dependencyMarker = `        .target(\n            name: "CapApp-SPM",\n            dependencies: [\n`;
  if (!source.includes(dependencyMarker)) {
    throw new Error("Capacitor SPM manifest shape changed; cannot install PolythLinkCore safely.");
  }
  source = source.replace(
    dependencyMarker,
    `${dependencyMarker}                "PolythLinkCore",\n`,
  );

  const targetEnd = `            ]\n        )\n    ]\n)\n`;
  if (!source.endsWith(targetEnd)) {
    throw new Error("Capacitor SPM target footer changed; cannot install PolythLinkCore safely.");
  }
  source = source.slice(0, -targetEnd.length) + `            ]\n        ),\n        .binaryTarget(\n            name: "PolythLinkCore",\n            path: "PolythLinkCore.xcframework"\n        )\n    ]\n)\n`;
  source = source.replace(
    "// DO NOT MODIFY THIS FILE - managed by Capacitor CLI commands",
    "// Generated by Capacitor, then patched by scripts/configure-ios-polyth-link.mjs.",
  );
  await writeFile(manifest, source);
}

const projectPath = resolve(here, "../ios/App/App.xcodeproj/project.pbxproj");
let project = await readFile(projectPath, "utf8");
if (!project.includes("PolythDiscoveryPlugin.swift in Sources")) {
  const fileRef = "A2D15C0D2F5A000000000001";
  const buildRef = "A2D15C0D2F5A000000000002";
  const buildMarker = "/* Begin PBXBuildFile section */\n";
  const fileMarker = "/* Begin PBXFileReference section */\n";
  const groupMarker = `\t\t504EC3061FED79650016851F /* App */ = {\n\t\t\tisa = PBXGroup;\n\t\t\tchildren = (\n`;
  const sourcesMarker = `\t\t504EC3001FED79650016851F /* Sources */ = {\n\t\t\tisa = PBXSourcesBuildPhase;\n\t\t\tbuildActionMask = 2147483647;\n\t\t\tfiles = (\n`;
  for (const marker of [buildMarker, fileMarker, groupMarker, sourcesMarker]) {
    if (!project.includes(marker)) {
      throw new Error("Xcode project shape changed; cannot install PolythDiscoveryPlugin safely.");
    }
  }
  project = project.replace(
    buildMarker,
    `${buildMarker}\t\t${buildRef} /* PolythDiscoveryPlugin.swift in Sources */ = {isa = PBXBuildFile; fileRef = ${fileRef} /* PolythDiscoveryPlugin.swift */; };\n`,
  );
  project = project.replace(
    fileMarker,
    `${fileMarker}\t\t${fileRef} /* PolythDiscoveryPlugin.swift */ = {isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = PolythDiscoveryPlugin.swift; sourceTree = "<group>"; };\n`,
  );
  project = project.replace(
    groupMarker,
    `${groupMarker}\t\t\t\t${fileRef} /* PolythDiscoveryPlugin.swift */,\n`,
  );
  project = project.replace(
    sourcesMarker,
    `${sourcesMarker}\t\t\t\t${buildRef} /* PolythDiscoveryPlugin.swift in Sources */,\n`,
  );
  await writeFile(projectPath, project);
}
