#!/usr/bin/env node
// The Homebrew formula of the packaged server, written from a release's
// SHA256SUMS-server.txt. It installs the release archive for the machine
// (macOS or Linux, arm64 or x64) into libexec, runs it with Homebrew's Node
// and gives `brew services` a service. The tap repository holds the result as
// Formula/polyth.rb (nightly.yml, stable releases only).
//
//   node scripts/ci/homebrew-formula.mjs <version> <SHA256SUMS-server.txt> [owner/repo] > polyth.rb
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { serverArchiveName } from "./update-feed.mjs";

/** Homebrew's OS and CPU blocks for each published platform. */
const BLOCKS = [
  { os: "on_macos", cpu: "on_arm", target: "darwin-arm64" },
  { os: "on_macos", cpu: "on_intel", target: "darwin-x64" },
  { os: "on_linux", cpu: "on_arm", target: "linux-arm64" },
  { os: "on_linux", cpu: "on_intel", target: "linux-x64" },
];

export function homebrewFormula({ version, sums, repository = "Polyth/Polyth" }) {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`Homebrew gets stable releases only, not ${version}`);
  const digests = new Map();
  for (const line of sums.split("\n")) {
    const match = /^([0-9a-f]{64}) {2}(\S+)$/.exec(line.trim());
    if (match) digests.set(match[2], match[1]);
  }
  const archive = (target) => {
    const name = serverArchiveName(version, target);
    const sha256 = digests.get(name);
    if (!sha256) throw new Error(`SHA256SUMS-server.txt has no ${name}`);
    return { url: `https://github.com/${repository}/releases/download/v${version}/${name}`, sha256 };
  };
  const block = (os) => BLOCKS.filter((entry) => entry.os === os).map(({ cpu, target }) => {
    const { url, sha256 } = archive(target);
    return [`    ${cpu} do`, `      url "${url}"`, `      sha256 "${sha256}"`, "    end"].join("\n");
  }).join("\n");
  return `# Generated by scripts/ci/homebrew-formula.mjs in ${repository}; edits are overwritten.
class Polyth < Formula
  desc "Server for running and supervising coding agents from any device"
  homepage "https://polyth.app"
  version "${version}"
  license "Apache-2.0"

  on_macos do
${block("on_macos")}
  end

  on_linux do
${block("on_linux")}
  end

  depends_on "node"

  def install
    libexec.install Dir["*"]
    (bin/"polyth").write <<~EOS
      #!/bin/bash
      exec "#{Formula["node"].opt_bin}/node" "#{libexec}/bin/polyth.mjs" "$@"
    EOS
  end

  def caveats
    <<~EOS
      First run, with the server stopped:
        polyth server setup-claim
      Then start it now and at login:
        brew services start polyth
      Update with \`brew upgrade polyth\`; \`polyth update\` leaves a Homebrew install to Homebrew.
    EOS
  end

  service do
    run [opt_bin/"polyth", "server", "start"]
    keep_alive successful_exit: false
    log_path var/"log/polyth.log"
    error_log_path var/"log/polyth.log"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/polyth --version").strip
  end
end
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [version, sumsFile, repository] = process.argv.slice(2);
  if (!version || !sumsFile) {
    console.error("usage: homebrew-formula.mjs <version> <SHA256SUMS-server.txt> [owner/repo]");
    process.exit(2);
  }
  process.stdout.write(homebrewFormula({ version, sums: readFileSync(sumsFile, "utf8"), ...(repository ? { repository } : {}) }));
}
