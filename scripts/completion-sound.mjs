#!/usr/bin/env node
// Synthesizes Polyth's completion chime and writes the two copies the web app
// ships: apps/web/src/assets/completion.mp3 and its base64 data URI in
// apps/web/src/assets/completionSound.ts. The sound is generated here from
// plain sine partials, so it is the project's own work under its license;
// no sample from elsewhere goes into it.
//
// Usage: node scripts/completion-sound.mjs  (needs ffmpeg with libmp3lame)
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const RATE = 44_100;
const LENGTH_S = 1.1;
/** A rising fifth (A5 → E6): each note is a soft bell, a fundamental with a
 *  few decaying overtones. */
const NOTES = [
  { at: 0, freq: 880, gain: 0.8 },
  { at: 0.085, freq: 1318.51, gain: 1 },
];
const PARTIALS = [
  { ratio: 1, gain: 1, decay: 0.42 },
  { ratio: 2, gain: 0.3, decay: 0.22 },
  { ratio: 3, gain: 0.1, decay: 0.13 },
  { ratio: 4.2, gain: 0.05, decay: 0.07 },
];
const ATTACK_S = 0.004;
const FADE_S = 0.06;
const PEAK = 10 ** (-3 / 20); // -3 dBFS

const samples = new Float64Array(Math.round(RATE * LENGTH_S));
for (const note of NOTES) {
  const start = Math.round(note.at * RATE);
  for (let i = start; i < samples.length; i++) {
    const t = (i - start) / RATE;
    const attack = Math.min(1, t / ATTACK_S);
    let value = 0;
    for (const partial of PARTIALS) {
      value += partial.gain * Math.exp(-t / partial.decay) * Math.sin(2 * Math.PI * note.freq * partial.ratio * t);
    }
    samples[i] += note.gain * attack * value;
  }
}
const fadeFrom = samples.length - Math.round(FADE_S * RATE);
for (let i = fadeFrom; i < samples.length; i++) samples[i] *= (samples.length - i) / (samples.length - fadeFrom);
const peak = samples.reduce((max, value) => Math.max(max, Math.abs(value)), 0);

const wav = Buffer.alloc(44 + samples.length * 2);
wav.write("RIFF", 0, "latin1");
wav.writeUInt32LE(36 + samples.length * 2, 4);
wav.write("WAVEfmt ", 8, "latin1");
wav.writeUInt32LE(16, 16);
wav.writeUInt16LE(1, 20); // PCM
wav.writeUInt16LE(1, 22); // mono
wav.writeUInt32LE(RATE, 24);
wav.writeUInt32LE(RATE * 2, 28);
wav.writeUInt16LE(2, 32);
wav.writeUInt16LE(16, 34);
wav.write("data", 36, "latin1");
wav.writeUInt32LE(samples.length * 2, 40);
samples.forEach((value, i) => wav.writeInt16LE(Math.round((value / peak) * PEAK * 32_767), 44 + i * 2));

const assets = resolve(dirname(fileURLToPath(import.meta.url)), "..", "apps", "web", "src", "assets");
const work = mkdtempSync(join(tmpdir(), "polyth-completion-sound-"));
try {
  const input = join(work, "completion.wav");
  const output = join(assets, "completion.mp3");
  writeFileSync(input, wav);
  const encoded = spawnSync("ffmpeg", [
    "-hide_banner", "-loglevel", "error", "-y",
    "-i", input,
    "-codec:a", "libmp3lame", "-b:a", "96k",
    "-id3v2_version", "3", "-fflags", "+bitexact", "-flags:a", "+bitexact",
    "-metadata", "title=Polyth completion",
    "-metadata", "comment=Synthesized by scripts/completion-sound.mjs",
    output,
  ], { stdio: "inherit" });
  if (encoded.status !== 0) throw new Error("ffmpeg could not encode the chime (is libmp3lame available?)");
  const base64 = readFileSync(output).toString("base64");
  writeFileSync(join(assets, "completionSound.ts"), [
    "// Base64-encoded audio/mpeg for instant, zero-latency playback across",
    "// browser, desktop and mobile webviews without HTTP range or scheme issues.",
    "// Generated by scripts/completion-sound.mjs together with completion.mp3.",
    "export const COMPLETION_SOUND_URI =",
    `  "data:audio/mpeg;base64,${base64}";`,
    "",
  ].join("\n"));
  console.log(`completion.mp3: ${readFileSync(output).length} bytes`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
