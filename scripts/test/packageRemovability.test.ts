const GENERATED_FROM_DISCOVERY = "// @generated by `npm run i18n:generate`";

interface Manifest {
  name?: string;
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
  peerDependencies?: Record<string, string>;
  optionalDependencies?: Record<string, string>;
}

const packageIds = readdirSync(join(root, "packages"), { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(join(root, "packages", entry.name, "package.json")))
  .map((entry) => entry.name)
  .sort();
const manifests = new Map(packageIds.map((id) =>
  [id, JSON.parse(readFileSync(join(root, "packages", id, "package.json"), "utf8")) as Manifest]));
const packageName = (id: string): string => manifests.get(id)?.name ?? `@polyth/${id}`;
const removable = packageIds.filter((id) => !(id in FRAMEWORK_PACKAGES));

const declares = (dependent: string, id: string): boolean => {
  const manifest = manifests.get(dependent);
  const name = packageName(id);
  return [manifest?.dependencies, manifest?.devDependencies, manifest?.peerDependencies, manifest?.optionalDependencies]
    .some((deps) => deps !== undefined && name in deps);
};

const escape = (value: string): string => value.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");

/** Directory names that only hold dependency trees or ignored build output.
 *  The containment check walks the filesystem so it can also run in a checkout
 *  without Git (for example a `git archive` export used to simulate package
 *  removal); skipping these keeps the file set identical to `git ls-files`. */
const SKIPPED_DIRECTORIES = new Set([
  "node_modules", ".git", ".scratch", "dist", "release", "target",
  "logs", "data", "artifacts", "_inbox", ".polyth", "__pycache__", "coverage",
]);

const SOURCE_FILE = /\.(ts|tsx|mjs|js|cjs|json|css)$/;

/** Repo-relative POSIX paths of files under `directory`, skipping dependency
 *  and build-output trees. */
function walkFiles(directory: string): string[] {
  const files: string[] = [];
  const visit = (current: string): void => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (!SKIPPED_DIRECTORIES.has(entry.name)) visit(join(current, entry.name));
      } else {
        files.push(relative(root, join(current, entry.name)).split(sep).join("/"));
      }
    }
  };
  visit(directory);
  return files;
}

function trackedSources(): string[] {
  return walkFiles(root).filter((file) => SOURCE_FILE.test(file) && !file.endsWith("package-lock.json")
    && !file.startsWith("docs/"));
}

/** Packages a file reaches through relative specifiers (`../../goals/x.ts`),
 *  which the name pattern alone cannot see. */
const relativeCache = new Map<string, Set<string>>();
function relativeTargets(file: string, source: string): Set<string> {
  let targets = relativeCache.get(file);
  if (targets) return targets;
  targets = new Set();
  for (const match of source.matchAll(/["'`](\.\.?\/[^"'`\s]+)["'`]/g)) {
    const target = relative(root, resolve(root, dirname(file), match[1]!)).split(sep).join("/");
    const id = owningPackage(target);
    if (id) targets.add(id);
  }
  relativeCache.set(file, targets);
  return targets;
}

function owningPackage(file: string): string | null {
  return /^packages\/([^/]+)\//.exec(file)?.[1] ?? null;
}

test("removable packages are named only by their declared dependents", () => {
  const files = trackedSources().map((file) => ({ file, source: readFileSync(join(root, file), "utf8") }));
  const leaks: string[] = [];
  const used = new Set<string>();
  for (const id of removable) {
    const pattern = new RegExp(`["'\`]${escape(packageName(id))}(?:/[^"'\`]*)?["'\`]|packages/${escape(id)}/`);
    for (const { file, source } of files) {
      const owner = owningPackage(file);
      if (owner === id || !(pattern.test(source) || relativeTargets(file, source).has(id))) continue;
      // Regenerated from discovery on every web build (apps/web/generateI18n.ts).
      if (source.startsWith(GENERATED_FROM_DISCOVERY)) continue;
      if (owner !== null && declares(owner, id)) continue;
      if (KNOWN_REFERENCES[file]?.[id] !== undefined) {
        used.add(`${file} -> ${id}`);
        continue;
      }
      leaks.push(`${file} -> ${id}`);
    }
  }
  assert.deepEqual(leaks, [], [
    "a removable package must be self-contained: the host and other packages reach it only through",
    "generic seams (slots, services, discovery). A package that genuinely builds on it declares it",
    "in its package.json dependencies. See .agents/skills/polyth-packages/package-structure.md §0.",
  ].join(" "));
  const stale = Object.entries(KNOWN_REFERENCES)
    .flatMap(([file, ids]) => Object.keys(ids).filter((id) => packageIds.includes(id)).map((id) => `${file} -> ${id}`))
    .filter((key) => !used.has(key));
  assert.deepEqual(stale, [], "remove KNOWN_REFERENCES entries that are no longer needed");
});

test("removable packages keep their data under directories named after their id", () => {
  const offenders: string[] = [];
  for (const id of removable) {
    const src = join(root, "packages", id, "src");
    if (!existsSync(src)) continue;
    const files = walkFiles(src).filter((file) => /\.(ts|tsx|mjs|js)$/.test(file));
    for (const file of files) {
      const source = readFileSync(join(root, file), "utf8");
      // `host.storageDir` is the shared deployment root. Removable packages
      // use packageDataDir(host) / adoptLegacyPackageData(host, …) or
      // host.spaceStorage(ctx).packageDir(id) instead.
      if (/\bhost\.storageDir\b/.test(source) && SHARED_ROOT_WRITERS[id] === undefined) offenders.push(file);
    }
  }
  assert.deepEqual(offenders, [], "write package data through packageDataDir(host) or spaceStorage(ctx).packageDir(id)");
  for (const id of Object.keys(SHARED_ROOT_WRITERS)) {
    // An entry for a package removed from this checkout is simply unused.
    assert.ok(!packageIds.includes(id) || removable.includes(id), `${id} in SHARED_ROOT_WRITERS is not a removable package`);
  }
});

test("framework classification only names packages that exist", () => {
  for (const id of Object.keys(FRAMEWORK_PACKAGES)) {
    assert.ok(packageIds.includes(id), `FRAMEWORK_PACKAGES names missing package ${id}`);
  }
  for (const file of Object.keys(KNOWN_REFERENCES)) {
    assert.ok(existsSync(join(root, file)), `KNOWN_REFERENCES names missing file ${file}`);
  }
});

test("the web shell uses only its own and framework translation keys", async () => {
  // A string key is a reference too: tr("ssh.…") in the shell breaks the
  // build (TranslationKey) once the ssh package and its catalog are gone.
  const owner = new Map<string, string>();
  for (const id of packageIds) {
    const exportsField = (manifests.get(id) as { exports?: Record<string, string> } | undefined)?.exports;
    const pattern = exportsField?.["./i18n/*"];
    if (!pattern) continue;
    const file = join(root, "packages", id, pattern.replace("*", "en"));
    if (!existsSync(file)) continue;
    const catalog = (await import(file) as { en?: Record<string, string> }).en ?? {};
    for (const key of Object.keys(catalog)) owner.set(key, id);
  }
  const offenders: string[] = [];
  const files = walkFiles(join(root, "apps/web/src"))
    .filter((file) => /\.(ts|tsx)$/.test(file) && !file.startsWith("apps/web/src/i18n/"));
  for (const file of files) {
    const source = readFileSync(join(root, file), "utf8");
    for (const match of source.matchAll(/\btr\(\s*["']([a-zA-Z][\w.-]*)["']/g)) {
      const id = owner.get(match[1]!);
      if (id && !(id in FRAMEWORK_PACKAGES)) offenders.push(`${file} -> ${id} (${match[1]})`);
    }
  }
  assert.deepEqual([...new Set(offenders)].sort(), [], "move the string into the shell catalog, or the UI into the package");
});
